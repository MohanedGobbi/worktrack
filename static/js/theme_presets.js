/**
 * Apply a theme preset to the document root
 */
function applyThemePreset(presetKey) {
    const preset = THEME_PRESETS[presetKey];
    if (!preset) return;
    
    const root = document.documentElement;
    if (preset.colors) {
        Object.entries(preset.colors).forEach(([prop, value]) => {
            root.style.setProperty(prop, value);
        });
    }
    
    // Update glass computed variables
    root.style.setProperty('--glass-bg', `color-mix(in srgb, var(--glass-bg-hex, ${preset.bgStart}) 85%, transparent)`);
    root.style.setProperty('--glass-border', `color-mix(in srgb, var(--glass-border-hex, #ffffff) 20%, transparent)`);
    root.style.setProperty('--glow-color', `color-mix(in srgb, var(--glow-color-hex, ${preset.primary}) 50%, transparent)`);
}

/**
 * Get a preview of all available themes for the theme picker
 */
function getThemePresets() {
    return THEME_PRESETS;
}

// Export for module usage
if (typeof window !== 'undefined') {
    window.THEME_PRESETS = THEME_PRESETS;
    window.applyThemePreset = applyThemePreset;
    window.getThemePresets = getThemePresets;
    window.hexToRgbStr = hexToRgbStr;
}
